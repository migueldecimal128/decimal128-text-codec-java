import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.junit.jupiter.api.Assertions.fail;

/**
 * The four conformance tables, over the shared {@code text_bid_dpd} corpus.
 *
 * <p>The vectors are read straight out of {@code resources/text_bid_dpd} -- the
 * {@code decimal128-resources} submodule -- and were generated by the
 * {@code decimal128-c} engine through its public API. That engine reaches its
 * answers by different algorithms than this codec does, so agreement is a
 * cross-check rather than a tautology.
 *
 * <pre>
 *   T1 DECODE  bid -&gt; text and dpd -&gt; text          (100, noncanonical)
 *   T2 ENCODE  text -&gt; bid and text -&gt; dpd          (100)
 *   T3 PARSE   input text -&gt; bits, both formats     (parse, 1,061 rows)
 *   T4 ERROR   malformed input text -&gt; rejection    (error, 173 rows)
 * </pre>
 *
 * <p>Plus the cross-format assertion: for every row both encodings must render
 * to the same text. That is the strongest property the corpus encodes.
 *
 * <p>The fifth table, {@code canonical}, is 84,783 rows of mostly common-path
 * volume and runs as {@link TestCanonicalCorpus}, the second class in this file.
 */
public class TestCorpusVectors {

    /** T1: every row's two encodings must render to the expected text. */
    @Test
    public void hundredDecodes() throws IOException {
        List<CorpusRow> rows = Corpus.load(Corpus.HUNDRED);
        assertEquals(100, rows.size());
        runDecodeTable(rows, "100");
    }

    /** T2: and the text must encode back to the same bits. */
    @Test
    public void hundredReEncodes() throws IOException {
        List<CorpusRow> rows = Corpus.load(Corpus.HUNDRED);
        assertEquals(100, rows.size());
        runEncodeTable(rows, "100");
    }

    /**
     * One-way rows: both encodings decode to the text, but at least one is a bit
     * pattern the canonical encoder would never emit, so re-encoding is
     * deliberately not asserted.
     */
    @Test
    public void nonCanonicalEncodingsRenderCorrectly() throws IOException {
        List<CorpusRow> rows = Corpus.load(Corpus.NON_CANONICAL);
        assertEquals(1267, rows.size());
        runDecodeTable(rows, "noncanonical");
    }

    /** T3: the only table that reaches the rounding surface at all. */
    @Test
    public void parseVectorsProduceBothEncodings() throws IOException {
        List<CorpusRow> rows = Corpus.load(Corpus.PARSE);
        assertEquals(1061, rows.size());
        for (CorpusRow row : rows) {
            ParseResult b = ParseResult.bidParse(row.text);
            assertNull(b.error, "parse line " + row.lineNumber + ": bid rejected <" + row.text + ">");
            assertEquals(row.bidHex, b.hex, "parse line " + row.lineNumber + ": bid <" + row.text + ">");
            ParseResult d = ParseResult.dpdParse(row.text);
            assertNull(d.error, "parse line " + row.lineNumber + ": dpd rejected <" + row.text + ">");
            assertEquals(row.dpdHex, d.hex, "parse line " + row.lineNumber + ": dpd <" + row.text + ">");
        }
    }

    /**
     * T4: malformed input. Both formats must reject, must agree on the message,
     * and must still have written the canonical positive quiet NaN -- the corpus
     * carries that pattern in its bits columns precisely so a port can assert the
     * written value and not merely the rejection.
     */
    @Test
    public void errorVectorsAreRejectedByBothFormats() throws IOException {
        List<CorpusRow> rows = Corpus.load(Corpus.ERROR);
        assertEquals(173, rows.size());
        for (CorpusRow row : rows) {
            ParseResult b = ParseResult.bidParse(row.text);
            ParseResult d = ParseResult.dpdParse(row.text);
            assertNotNull(b.error,
                "error line " + row.lineNumber + ": bid ACCEPTED <" + row.text + ">, corpus says " + row.status);
            assertNotNull(d.error,
                "error line " + row.lineNumber + ": dpd ACCEPTED <" + row.text + ">, corpus says " + row.status);
            assertEquals(b.error, d.error,
                "error line " + row.lineNumber + ": the formats disagree on <" + row.text + ">");
            assertEquals(row.bidHex, b.hex, "error line " + row.lineNumber + ": bid <" + row.text + ">");
            assertEquals(row.bidHex, d.hex, "error line " + row.lineNumber + ": dpd <" + row.text + ">");
        }
    }

    /**
     * The reader itself. {@code parse} and {@code error} quote their text column,
     * and the four rows below are exactly the ones a naive comma split corrupts
     * while still passing -- a mangled malformed input fails to parse either way.
     */
    @Test
    public void quotedColumnRoundTrips() throws IOException {
        Set<String> texts = new HashSet<>();
        for (CorpusRow row : Corpus.load(Corpus.ERROR))
            texts.add(row.text);
        assertTrue(texts.contains(""), "the empty-string row was lost");
        assertTrue(texts.stream().anyMatch(t -> t.startsWith(" ")), "a leading-space row was lost");
        assertTrue(texts.stream().anyMatch(t -> t.endsWith(" ")), "a trailing-space row was lost");
        assertTrue(texts.stream().anyMatch(t -> t.contains(",")), "an embedded-comma row was lost");
    }

    /**
     * Every row: both encodings must render to the expected text, and
     * therefore to each other.
     *
     * <p>Each row is rendered twice, once through the {@code String} form and
     * once into a caller-supplied buffer, and both must produce the expected
     * text. The two forms are separate implementations -- the {@code String}
     * one keeps its interned constants, the buffer one allocates nothing -- so
     * this is what pins them together.
     */
    static void runDecodeTable(List<CorpusRow> rows, String label) {
        byte[] buf = new byte[Decimal128TextCodec.MAX_LEN];
        for (CorpusRow row : rows) {
            assertEquals(row.text, Decimal128TextCodec.bid128ToString(row.bidHi(), row.bidLo()),
                label + " line " + row.lineNumber + ": bid #" + row.bidHex);
            assertEquals(row.text, Decimal128TextCodec.dpd128ToString(row.dpdHi(), row.dpdLo()),
                label + " line " + row.lineNumber + ": dpd #" + row.dpdHex);
            int bidLen = Decimal128TextCodec.bid128ToString(buf, row.bidHi(), row.bidLo());
            assertEquals(row.text, new String(buf, 0, bidLen, StandardCharsets.ISO_8859_1),
                label + " line " + row.lineNumber + ": bid into buffer #" + row.bidHex);
            int dpdLen = Decimal128TextCodec.dpd128ToString(buf, row.dpdHi(), row.dpdLo());
            assertEquals(row.text, new String(buf, 0, dpdLen, StandardCharsets.ISO_8859_1),
                label + " line " + row.lineNumber + ": dpd into buffer #" + row.dpdHex);
        }
    }

    /** Round-trippable rows: the text must encode back to the same bits. */
    static void runEncodeTable(List<CorpusRow> rows, String label) {
        for (CorpusRow row : rows) {
            ParseResult b = ParseResult.bidParse(row.text);
            assertNull(b.error, label + " line " + row.lineNumber + ": bid rejected <" + row.text + ">");
            assertEquals(row.bidHex, b.hex, label + " line " + row.lineNumber + ": bid <" + row.text + ">");
            ParseResult d = ParseResult.dpdParse(row.text);
            assertNull(d.error, label + " line " + row.lineNumber + ": dpd rejected <" + row.text + ">");
            assertEquals(row.dpdHex, d.hex, label + " line " + row.lineNumber + ": dpd <" + row.text + ">");
        }
    }
}

/**
 * The full canonical table: 84,783 rows, read from the same submodule as the
 * rest. It is a separate class only because it is two orders of magnitude bigger
 * than the other four put together, not because it is optional -- keeping it
 * here rather than in a file of its own is what lets the two table runners above
 * stay package-private to this file.
 */
class TestCanonicalCorpus {

    @Test
    public void canonicalTableDecodesAndReEncodes() throws IOException {
        List<CorpusRow> rows = Corpus.load(Corpus.CANONICAL);
        assertEquals(84783, rows.size());
        TestCorpusVectors.runDecodeTable(rows, "canonical");
        TestCorpusVectors.runEncodeTable(rows, "canonical");
    }
}

/**
 * One row of a {@code text_bid_dpd} table: the text, the two encodings as 32 bare
 * uppercase hex digits, and the {@code status} column the input-driven tables carry.
 */
class CorpusRow {

    final String text;
    final String bidHex;
    final String dpdHex;
    final String status;
    final int lineNumber;

    CorpusRow(String text, String bidHex, String dpdHex, String status, int lineNumber) {
        this.text = text;
        this.bidHex = bidHex;
        this.dpdHex = dpdHex;
        this.status = status;
        this.lineNumber = lineNumber;
    }

    long bidHi() {
        return Hex.hi(bidHex);
    }

    long bidLo() {
        return Hex.lo(bidHex);
    }

    long dpdHi() {
        return Hex.hi(dpdHex);
    }

    long dpdLo() {
        return Hex.lo(dpdHex);
    }
}

/** Hex, in the corpus column form: 32 uppercase digits, most-significant first. */
final class Hex {

    private Hex() {
    }

    /** The high word of a 32-digit hex encoding. */
    static long hi(String h) {
        return Long.parseUnsignedLong(h.substring(0, 16), 16);
    }

    /** The low word of a 32-digit hex encoding. */
    static long lo(String h) {
        return Long.parseUnsignedLong(h.substring(16, 32), 16);
    }

    /** An encoding rendered the way the corpus spells it: 32 uppercase hex digits. */
    static String format32(long a, long b) {
        return pad16(a) + pad16(b);
    }

    private static String pad16(long v) {
        String s = Long.toHexString(v).toUpperCase();
        return "0".repeat(16 - s.length()) + s;
    }
}

/**
 * The shared conformance corpus, read from {@code resources/text_bid_dpd} -- the
 * {@code decimal128-resources} submodule, mounted at the repo root the way every
 * decimal128 port mounts it. Nothing is copied into this repo.
 *
 * <p>The row counts are asserted by the tests, and that is not ceremony: the text
 * column of {@code parse} and {@code error} is double-quoted with {@code \\} and
 * {@code \"} escapes, because those tables must carry the empty string, a leading
 * and a trailing space, an embedded comma, an embedded quote and an embedded
 * backslash. The other three leave it bare. A naive comma split silently corrupts
 * four rows and still passes, since a mangled malformed input fails to parse
 * either way. The row count is what catches it.
 *
 * <p>The Kotlin port needs a KMP {@code expect}/{@code actual} seam to reach a data
 * file at all; the JVM reads it directly, so the loader is three lines here and
 * lives with its only caller.
 */
final class Corpus {

    private Corpus() {
    }

    static final String DIRECTORY = "/text_bid_dpd";

    static final String HUNDRED = "text_bid128_dpd128_100";
    static final String NON_CANONICAL = "text_bid128_dpd128_noncanonical";
    static final String PARSE = "text_bid128_dpd128_parse";
    static final String ERROR = "text_bid128_dpd128_error";
    static final String CANONICAL = "text_bid128_dpd128_canonical";

    /** Where the loader looked, for an error message that names the fix. */
    static final String RESOURCES_HINT =
        "the decimal128-resources submodule is not checked out: "
            + "run `git submodule update --init --recursive`";

    /**
     * The corpus is read off the filesystem, not the test classpath. Nothing is
     * copied into {@code src/test/resources}, so there is no classpath copy to go
     * stale -- the submodule working tree is the only version there is. The build
     * hands the absolute root over in {@code DECIMAL128_RESOURCES}, so no runner's
     * working directory matters.
     */
    private static String loadTestResourceAsString(String fileName) throws IOException {
        String base = System.getenv("DECIMAL128_RESOURCES");
        if (base == null)
            base = "resources";
        Path path = Path.of(base + fileName);
        if (!Files.isRegularFile(path))
            return null;
        return Files.readString(path, StandardCharsets.UTF_8);
    }

    /** One table, read through the loader. */
    static List<CorpusRow> load(String name) throws IOException {
        String path = DIRECTORY + "/" + name + ".csv.txt";
        String contents = loadTestResourceAsString(path);
        if (contents == null)
            fail(path + " could not be read -- " + RESOURCES_HINT);
        return parseTable(contents, name);
    }

    private static List<CorpusRow> parseTable(String contents, String name) {
        List<CorpusRow> rows = new ArrayList<>();
        int lineNumber = 0;
        for (String rawLine : contents.split("\n", -1)) {
            ++lineNumber;
            String line = rawLine;
            while (line.endsWith("\r"))
                line = line.substring(0, line.length() - 1);
            line = skipSpace(line);
            if (line.isEmpty() || line.startsWith("#"))
                continue;

            String text;
            Field first = line.startsWith("\"") ? readQuoted(line) : readField(line);
            text = first.value;
            line = first.rest;

            Field bid = readNextField(line);
            Field dpd = readNextField(bid.rest);
            Field status = readNextField(dpd.rest);

            String bidHex = normalizeHex(bid.value);
            String dpdHex = normalizeHex(dpd.value);
            if ((bidHex == null) || (dpdHex == null)) {
                fail(name + ".csv.txt line " + lineNumber + ": malformed hex columns <"
                    + bid.value + "> <" + dpd.value + ">");
            }
            rows.add(new CorpusRow(text, bidHex, dpdHex, status.value, lineNumber));
        }
        return rows;
    }

    /** {@code 0x} + 32 hex digits, or 32 bare ones, normalized to bare uppercase. */
    private static String normalizeHex(String field) {
        String body = (field.startsWith("0x") || field.startsWith("0X")) ? field.substring(2) : field;
        if (body.length() != 32)
            return null;
        for (int i = 0; i < body.length(); ++i) {
            char c = body.charAt(i);
            if (!((c >= '0' && c <= '9') || (c >= 'a' && c <= 'f') || (c >= 'A' && c <= 'F')))
                return null;
        }
        return body.toUpperCase();
    }

    // -- the reader, matching the C and Swift ports ---------------------------

    /** One field and the unconsumed rest of the line. */
    private record Field(String value, String rest) {
    }

    private static String skipSpace(String s) {
        int i = 0;
        while ((i < s.length()) && ((s.charAt(i) == ' ') || (s.charAt(i) == '\t')))
            ++i;
        return s.substring(i);
    }

    /**
     * One comma-delimited field, stopping at {@code ,} or {@code #} or end of line,
     * with surrounding whitespace trimmed. Returns the field and the unconsumed rest.
     */
    private static Field readField(String s) {
        String start = skipSpace(s);
        int end = 0;
        while ((end < start.length()) && (start.charAt(end) != ',') && (start.charAt(end) != '#'))
            ++end;
        int trim = end;
        while ((trim > 0) && ((start.charAt(trim - 1) == ' ') || (start.charAt(trim - 1) == '\t')))
            --trim;
        return new Field(start.substring(0, trim), start.substring(end));
    }

    /**
     * Step over a field separator, then read the next field. Yields the empty
     * string when the row has no further column.
     */
    private static Field readNextField(String s) {
        String rest = skipSpace(s);
        if (!rest.startsWith(","))
            return new Field("", rest);
        return readField(rest.substring(1));
    }

    /** The quoted text column, honouring {@code \\} and {@code \"} escapes. */
    private static Field readQuoted(String s) {
        StringBuilder out = new StringBuilder();
        int i = 1; // past the opening quote
        while ((i < s.length()) && (s.charAt(i) != '"')) {
            char c = s.charAt(i);
            ++i;
            if ((c == '\\') && (i < s.length())) {
                c = s.charAt(i);
                ++i;
            }
            out.append(c);
        }
        if ((i < s.length()) && (s.charAt(i) == '"'))
            ++i;
        return new Field(out.toString(), s.substring(i));
    }
}

// ---------------------------------------------------------------------------
// Thin wrappers so the tests read the way the codec's own API does.
// ---------------------------------------------------------------------------

final class ParseResult {

    final String hex;
    final String error;

    private ParseResult(String hex, String error) {
        this.hex = hex;
        this.error = error;
    }

    static ParseResult bidParse(String text) {
        long[] bits = {0xFEEDL, 0xFACEL};
        String err = Decimal128TextCodec.bid128Parse(bits, text);
        return new ParseResult(Hex.format32(bits[0], bits[1]), err);
    }

    static ParseResult dpdParse(String text) {
        long[] bits = {0xFEEDL, 0xFACEL};
        String err = Decimal128TextCodec.dpd128Parse(bits, text);
        return new ParseResult(Hex.format32(bits[0], bits[1]), err);
    }
}
